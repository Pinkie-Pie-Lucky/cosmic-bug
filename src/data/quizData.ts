// 计算算法逻辑：输入一个已选答案的数组（长度为 12，值为 'A' | 'B' | 'C' | 'D'）
// 返回匹配结果
export function calculateResult(answers: ('A' | 'B' | 'C' | 'D')[]) {
  // 1. 初始化用户六维累加分与标签
  const user6DAccum = { R: 0, A: 0, E: 0, I: 0, C: 0, U: 0 };
  const tagCounts = { EX: 0, MO: 0, OB: 0, ST: 0 };

  answers.forEach((ans, idx) => {
    const q = QUESTIONS[idx];
    const opt = q.options[ans];
    
    // 累加标签
    tagCounts[opt.tag] += 1;

    // 累加六维维度分
    Object.keys(opt.scores).forEach((dim) => {
      user6DAccum[dim as keyof typeof user6DAccum] += opt.scores[dim];
    });
  });

  // 2. 归一化 (转换为 0~100 的百分制)
  const U_6D = {
    R: (user6DAccum.R / DIMENSION_MAX.R) * 100,
    A: (user6DAccum.A / DIMENSION_MAX.A) * 100,
    E: (user6DAccum.E / DIMENSION_MAX.E) * 100,
    I: (user6DAccum.I / DIMENSION_MAX.I) * 100,
    C: (user6DAccum.C / DIMENSION_MAX.C) * 100,
    U: (user6DAccum.U / DIMENSION_MAX.U) * 100,
  };

  // 3. 计算每个选项对应的核心标签百分制得分 (选一次 8.33 分，12次刚好 100 分)
  const U_Tag = {
    EX: tagCounts.EX * 8.33,
    MO: tagCounts.MO * 8.33,
    OB: tagCounts.OB * 8.33,
    ST: tagCounts.ST * 8.33,
  };

  // 4. 计算加权欧氏距离并得出匹配分
  const candidates = PERSONALITIES.map((p) => {
    // 维度欧氏距离
    const distance6D = Math.sqrt(
      DIMENSION_WEIGHTS.R * Math.pow(U_6D.R - p.scores.R, 2) +
      DIMENSION_WEIGHTS.A * Math.pow(U_6D.A - p.scores.A, 2) +
      DIMENSION_WEIGHTS.E * Math.pow(U_6D.E - p.scores.E, 2) +
      DIMENSION_WEIGHTS.I * Math.pow(U_6D.I - p.scores.I, 2) +
      DIMENSION_WEIGHTS.C * Math.pow(U_6D.C - p.scores.C, 2) +
      DIMENSION_WEIGHTS.U * Math.pow(U_6D.U - p.scores.U, 2)
    );

    const S_6D = 100 - distance6D;

    // 标签相似度 (标准欧氏距离)
    const distanceTag = Math.sqrt(
      Math.pow(U_Tag.EX - p.tags.EX, 2) +
      Math.pow(U_Tag.MO - p.tags.MO, 2) +
      Math.pow(U_Tag.OB - p.tags.OB, 2) +
      Math.pow(U_Tag.ST - p.tags.ST, 2)
    );

    const S_Tag = 100 - distanceTag;

    return {
      personality: p,
      S_6D,
      S_Tag,
    };
  });

  // 按 S_6D 降序排列
  candidates.sort((a, b) => b.S_6D - a.S_6D);

  const Top1 = candidates[0];
  const Top2 = candidates[1];
  const Top3 = candidates[2];

  let finalPersonality: Personality;
  let triggerTagCorrection = false;
  let finalCompositeScore = 100;

  // 5. 三级过滤与标签修正判定 (阈值为 0.15 分)
  if ((Top1.S_6D - Top2.S_6D >= 0.15) && (Top1.S_6D - Top3.S_6D >= 0.15)) {
    // 情况 A：绝对碾压，无撞车风险
    finalPersonality = Top1.personality;
    finalCompositeScore = Top1.S_6D;
  } else {
    // 情况 B：数据纠缠，触发标签修正机制
    triggerTagCorrection = true;

    // 计算复合得分 (80% 维度匹配 + 20% 标签匹配)
    const scoreTop1Comp = Top1.S_6D * 0.8 + Top1.S_Tag * 0.2;
    const scoreTop2Comp = Top2.S_6D * 0.8 + Top2.S_Tag * 0.2;
    const scoreTop3Comp = Top3.S_6D * 0.8 + Top3.S_Tag * 0.2;

    const comps = [
      { cand: Top1, compScore: scoreTop1Comp },
      { cand: Top2, compScore: scoreTop2Comp },
      { cand: Top3, compScore: scoreTop3Comp }
    ];

    comps.sort((a, b) => b.compScore - a.compScore);

    finalPersonality = comps[0].cand.personality;
    finalCompositeScore = comps[0].compScore;
  }

  return {
    personality: finalPersonality,
    compositeScore: finalCompositeScore,
    userScores: U_6D,
    userTags: U_Tag,
    triggerTagCorrection,
    topCandidates: [Top1, Top2, Top3].map(c => ({
      name: c.personality.name,
      id: c.personality.id,
      S_6D: c.S_6D,
      S_Tag: c.S_Tag,
      composite: c.S_6D * 0.8 + c.S_Tag * 0.2
    }))
  };
}
